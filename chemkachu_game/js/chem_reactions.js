const REACTION_MAP = new Map();

for (const rx of REACTION_DATABASE) {
  REACTION_MAP.set(`${rx.a}|${rx.b}`, rx);
  REACTION_MAP.set(`${rx.b}|${rx.a}`, rx);
}

/**
 * Kiểm tra cặp chất A & B có phản ứng hóa học hay không (Độ phức tạp O(1))
 */
export function checkChemicalReaction(substanceA, substanceB) {
  if (!substanceA || !substanceB || substanceA === substanceB) {
    return { valid: false };
  }

  const match = REACTION_MAP.get(`${substanceA}|${substanceB}`);
  return match ? { valid: true, data: match } : { valid: false };
}

/**
 * Trích xuất danh sách toàn bộ chất hóa học duy nhất (Phục vụ Từ điển / Gợi ý)
 */
export function getAllUniqueSubstances() {
  const uniqueSet = new Set();
  for (const rx of REACTION_DATABASE) {
    uniqueSet.add(rx.a);
    uniqueSet.add(rx.b);
  }
  return Array.from(uniqueSet).sort();
}